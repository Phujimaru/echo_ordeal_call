export default function NautilusGuide({ state, onClose }) {
  useEffect(() => {
    const onKey = (e) => { if (e.key === "Escape") onClose(); };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [onClose]);
  const fd = state.fodlan || {};
  const list = NT_GUIDE[fd.stage] || [];
  const whale = fd.whaleEnabled !== false;
  const row = ([icon, name, text], i) => (
    <li key={i} data-tone="ok">
      <span className="ico">{icon}</span>
      <span className="txt"><b>{name}</b><span className="det">{text}</span></span>
    </li>
  );
  return (
    <div className="eos-sit-back" onClick={onClose}>
      <div className="eos-sit nt-panel" role="dialog" aria-label="ลูกเล่น" onClick={(e) => e.stopPropagation()}>
        <header><b>{fd.name || "Nautilus"}</b><span>ลูกเล่น</span><button type="button" aria-label="ปิด" onClick={onClose}>✕</button></header>
        <ul>
          {list.map(row)}
          {NT_COMMON.filter((r) => (whale || r[1] !== "เหยื่อล่อปลาวาฬ") && !(Number(fd.stage) === 12 && (r[1] === "ออกซิเจน" || r[1] === "เรือ: เติมออกซิเจน"))).map((r, i) => row(r, `c${i}`))}
        </ul>
      </div>
    </div>
  );
}
