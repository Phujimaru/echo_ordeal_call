  magitek: { icon: "🤖", name: "ทหารเหล็ก", desc: "ลงจากยานจักรวรรดิ (กลางวันลงบ่อย หลายจุด) · มุ่งไปตีเสาที่ยึดไว้ก่อน · อยู่ 4 เทิร์นแล้วขึ้นยานกลับ · ล้มได้ = เหรียญ + ของ/ขวดเวท" },
