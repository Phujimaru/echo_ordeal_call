export default function EosGuide({ onClose }) {
  const [tab, setTab] = useState("goal");
  useEffect(() => {
    const onKey = (e) => { if (e.key === "Escape") onClose(); };
    window.addEventListener("keydown", onKey);
    return () => window.removeEventListener("keydown", onKey);
  }, [onClose]);
  const cur = TABS.find((t) => t.id === tab) || TABS[0];
  return (
    <div className="eos-guide-back" onClick={onClose}>
      <div className="eos-guide" role="dialog" aria-label="คู่มือ Eos" onClick={(e) => e.stopPropagation()}>
        <header>
          <h2>Eos</h2>
          <button type="button" className="eos-guide-x" aria-label="ปิด" onClick={onClose}>✕</button>
        </header>
        <nav role="tablist">
          {TABS.map((t) => (
            <button key={t.id} type="button" role="tab" aria-selected={t.id === tab} data-on={t.id === tab ? "true" : undefined} onClick={() => setTab(t.id)}>
              <span>{t.icon}</span>{t.name}
            </button>
          ))}
        </nav>
        <ul>
          {cur.rows.map(([ico, name, desc]) => (
            <li key={name}><span className="ico">{ico}</span><b>{name}</b><p>{desc}</p></li>
          ))}
        </ul>
      </div>
    </div>
  );
}
