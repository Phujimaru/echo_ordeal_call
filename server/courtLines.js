function fill(text, ctx = {}) {
  return String(text).replace(/\{(\w+)\}/g, (m, k) => (ctx[k] != null && ctx[k] !== "" ? String(ctx[k]) : m === "{target}" ? "ใครสักคน" : m === "{skill}" ? "ท่านั้น" : ""));
}
// สุ่ม 1 บรรทัด · used = array ของ "key#index" ที่ใช้ไปแล้วในคดีนี้ (ไม่ซ้ำจนกว่ากองนั้นจะหมด)
function pick(key, ctx, used, rng = Math.random) {
  const pool = POOLS[key] || STATEMENTS[key];
  if (!pool || !pool.length) return "";
  let idx = pool.map((_, i) => i);
  if (Array.isArray(used)) {
    const free = idx.filter((i) => !used.includes(`${key}#${i}`));
    if (!free.length) { for (let i = used.length - 1; i >= 0; i--) if (used[i].startsWith(`${key}#`)) used.splice(i, 1); }
    else idx = free;
  }
  const i = idx[Math.floor(rng() * idx.length)];
  if (Array.isArray(used)) used.push(`${key}#${i}`);
  return fill(pool[i], ctx);
}
// เวลาอ่านของข้อความ (ms) — client เล่นตามนี้
function readMs(text) {
  return Math.max(1600, Math.min(4200, 900 + String(text).length * 45));
}

