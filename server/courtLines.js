// ผู้พูดขึ้นชื่อในกล่องข้อความอยู่แล้ว (say.name) — ตัด "{G}: " / "{C}: " หน้าบรรทัดออก (เขียนไว้ให้อ่านไฟล์นี้ง่าย)
