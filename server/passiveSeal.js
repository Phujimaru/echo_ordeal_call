//  · ใส่ผ่าน engine.applyPassiveSeal(p, turns) เท่านั้น (= applyDebuff "noPassive" — เคารพต้านสถานะ/สะท้อน/ชั้นมิติ/ทีม)
//  · ลดลงทีละเทิร์นตอนจบเทิร์นแบบดีบัฟทั่วไป · อยู่ใน BASIC_DEBUFF_CLEAR (ต้านสถานะ/ล้างดีบัฟล้างได้)
//  · โค้ดสกิลติดตัวของทุกตัวละครต้องเช็ค PassiveSeal.on(p) ก่อนทำงาน (ไม่มีตัวกรองฮุคอัตโนมัติ — ฮุคตัวละครผสมทั้งสกิลกดและสกิลติดตัว)
//    → ตัวละครใหม่ที่มีสกิลติดตัวต้องเช็คเอง (add-character SKILL.md · GAME_SYSTEM.md "ลบสกิลติดตัว")
//  · ไม่กระทบ: ค่าพื้นฐาน (HP/เกราะ/เดิน/ระยะตี) · ผลของสกิลกด/ท่าไม้ตาย/อาวุธ/ร่างที่กดแปลง · สถานะที่ติดไปแล้ว
//    · ค่าสะสมของสกิลติดตัวไม่หาย (แค่ไม่เพิ่ม/ไม่ออกฤทธิ์ระหว่างติด)
//  ไฟล์นี้ไม่ require อะไร — require ได้จากทุกที่โดยไม่วน
// ============================================================
const KEY = "noPassive";
const sealed = (p) => !!p && ((p.statuses && p.statuses[KEY]) || 0) > 0;
const on = (p) => !sealed(p);
module.exports = { KEY, sealed, on };
