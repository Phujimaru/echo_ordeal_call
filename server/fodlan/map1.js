// ด่าน 1 ของโหมด Fodlan "แม่น้ำแอร์มิด" — ผังกระดาน + ชนิดช่องใหม่ (ข้อมูลล้วน · ดู server/fodlan/README.md · กติกา server/fodlan/stage1.js)
//  ป่าธรรมดา + แม่น้ำใหญ่ไหลจากตะวันตกไปตะวันออก (กว้าง 3 ช่อง คดลงกลางแผนที่แล้วขึ้น) แบ่งกระดานเป็นฝั่งเหนือ/ใต้
//  ข้ามแม่น้ำได้ 2 ทางเท่านั้น (ผู้ใช้ตัดสิน): เรือลำใหญ่ 2×3 (ของกลาง ขับไปตามแม่น้ำ) · น้ำแข็ง (Ice Spike) บนแม่น้ำ = สะพาน
//  ผัง (x = 0..13 ซ้าย→ขวา · y = 0..13 เหนือ→ใต้):
//   ~ แม่น้ำ (fd_river — สิ่งกีดขวาง)  # สน (fd_riverpine)  o ต้นไม้ใบกว้าง (fd_riveroak)  L คันโยก (fd_lever)
//   f ป่าทึบ (forest — ซ่อนตัว)  D ท่าเรือ (พื้นธรรมดา — วาดจาก publicInfo)  S จุดเกิด  $ จุดร้านค้า
//  เรือจอดเทียบท่า (มุมบนซ้ายของเรือ 3 กว้าง × 2 สูง): ฝั่งเหนือ (9, 5) · ฝั่งใต้ (3, 6) — ช่องเรือในผังเป็นแม่น้ำ (ชั้น layer ของ stage1.js เปิดให้เดินได้)
const ROWS = [
  "#..o..S......#", // y0
  ".S....ff.#.So.", // y1
  "...$..ff..$..f", // y2
  ".~...o......ff", // y3
  "~~~.#...LDDD~~", // y4  ท่าเรือฝั่งเหนือ + คันโยก
  "~~~~~~...~~~~~", // y5
  "~~~~~~~~~~~~~~", // y6
  "...~~~~~~~~~~.", // y7
  "#.LDDD~~~.....", // y8  ท่าเรือฝั่งใต้ + คันโยก
  "ff....~~......", // y9
  "..o$ff.$..ff.S", // y10
  "....ff..#.f...", // y11
  ".S....o..S.$o.", // y12
  "o....S.......#", // y13
];
const at = (ch) => {
  const out = [];
  ROWS.forEach((row, y) => [...row].forEach((c, x) => { if (c === ch) out.push([x, y]); }));
  return out;
};

module.exports = {
  map: {
    terrain: { fd_river: at("~"), fd_riverpine: at("#"), fd_riveroak: at("o"), fd_lever: at("L") },
    special: { forest: at("f") },
    heal: [],
    spawns: at("S"),
    shopSpots: at("$"),
  },
  // iceBridge = สิ่งกีดขวางที่วางธารน้ำแข็งทับได้ (server/ice.js canLay/layIce) → กลายเป็นสะพานน้ำแข็ง (ชั้น layer ของ stage1.js)
  TERRAIN: {
    fd_river: { name: "แม่น้ำ", icon: "🌊", desc: "แม่น้ำ", iceBridge: true },
  },
  // ท่าเรือ 2 ฝั่ง: ช่องท่า (D) · คันโยก (L) · มุมบนซ้ายของเรือตอนจอด (เรือ 3×2)
  BOAT_W: 3,
  BOAT_H: 2,
  DOCKS: [
    { side: "n", tiles: [[9, 4], [10, 4], [11, 4]], lever: [8, 4], anchor: [9, 5] },
    { side: "s", tiles: [[3, 8], [4, 8], [5, 8]], lever: [2, 8], anchor: [3, 6] },
  ],
};
